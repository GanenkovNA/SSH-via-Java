package io.github.ganenkovna.ssh.commands.ip.a.dto;

/**
 * Минимальное представление IP-адреса, назначенного сетевому интерфейсу.
 *
 * <p>Интерфейс предназначен для быстрых проверок наличия IP-адресов
 * на интерфейсе без привязки к конкретной версии протокола (IPv4 / IPv6)
 * и без учёта дополнительных атрибутов адреса.</p>
 *
 * <p>Типично используется в тестовых утилитах и предикатах, например
 * при проверке того, что интерфейс содержит указанный адрес
 * (см. {@code IpAddrTestSupport.hasInterfaceIpAddress}).</p>
 *
 * <p>Реализации интерфейса являются простыми DTO и не гарантируют
 * потокобезопасность.</p>
 */
public interface IpAddrInfo {
  /**
   * Возвращает локальный IP-адрес интерфейса в строковом виде.
   *
   * <p>Формат зависит от версии протокола:</p>
   * <ul>
   *   <li>IPv4 — десятичная запись с точками (например, {@code 192.168.1.10})</li>
   *   <li>IPv6 — стандартная текстовая форма (например, {@code fe80::1})</li>
   * </ul>
   *
   * <p>Значение всегда соответствует полю {@code local}
   * из JSON-вывода команды {@code ip -j addr}.</p>
   *
   * @return строковое представление IP-адреса; никогда не {@code null}
   */
  String local();

  /**
   * Возвращает длину сетевого префикса IP-адреса.
   *
   * <p>Значение соответствует CIDR-префиксу адреса
   * (например, {@code 24} для {@code 192.168.1.10/24},
   * {@code 64} для {@code fe80::1/64}).</p>
   *
   * <p>Диапазон допустимых значений определяется версией протокола
   * (IPv4 или IPv6) и не проверяется на уровне данного интерфейса.</p>
   *
   * @return длина префикса; никогда не {@code null}
   */
  Integer prefixlen();
}
