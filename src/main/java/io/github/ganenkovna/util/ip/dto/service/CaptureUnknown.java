package io.github.ganenkovna.util.ip.dto.service;

/**
 * Контракт для перехвата и сохранения неизвестных полей или значений,
 * обнаруженных при десериализации данных (например, через Jackson).
 *
 * <p>Используется в DTO и вспомогательных структурах для сохранения информации
 * о полях, которые отсутствуют в явной модели, но присутствуют во входных данных
 * (JSON, вывод CLI-команд и т.п.). Это позволяет:</p>
 *
 * <ul>
 *   <li>не терять данные при строгой десериализации;</li>
 *   <li>анализировать или логировать неизвестные параметры;</li>
 *   <li>обеспечивать прямую и обратную совместимость форматов.</li>
 * </ul>
 *
 * <p>Типичное использование — в сочетании с {@code @JsonAnySetter} Jackson,
 * когда каждое неизвестное поле передаётся в реализацию этого интерфейса.</p>
 *
 * <p>Контракт интерфейса не накладывает ограничений на способ хранения
 * неизвестных значений (например, {@code Map<String, Object>}), но реализации
 * должны явно документировать свои правила:</p>
 *
 * <ul>
 *   <li>допускается ли {@code null} в значениях;</li>
 *   <li>поддерживается ли повторное добавление одного и того же поля;</li>
 *   <li>является ли реализация потокобезопасной.</li>
 * </ul>
 *
 * @see com.fasterxml.jackson.annotation.JsonAnySetter
 */
public interface CaptureUnknown {

  /**
   * Захватывает неизвестное поле и его значение.
   *
   * <p>Метод вызывается при обнаружении параметра, который не имеет
   * явного отображения в целевой модели данных.</p>
   *
   * @param field имя неизвестного поля;
   *              строго не {@code null} и не пустая строка
   * @param value значение поля;
   *              может быть {@code null}, если это допускается
   *              входным форматом или реализацией
   *
   * @throws NullPointerException если {@code field == null}
   * @throws IllegalArgumentException если {@code field} является пустой строкой
   */
  void captureUnknown(String field, Object value);
}
